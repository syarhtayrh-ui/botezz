export function getPaginatedOsintCatalog(
  page: number,
  pageSize = 12
): {
  page: number;
  totalPages: number;
  totalTools: number;
  items: ApprovedOsintToolEntry[];
} {
  const totalTools = APPROVED_OSINT_TOOLS_CATALOG.length;
  const totalPages = Math.max(1, Math.ceil(totalTools / pageSize));
  const safePage = Math.max(1, Math.min(page, totalPages));
  const start = (safePage - 1) * pageSize;
  return {
    page: safePage,
    totalPages,
    totalTools,
    items: APPROVED_OSINT_TOOLS_CATALOG.slice(start, start + pageSize),
  };
}
